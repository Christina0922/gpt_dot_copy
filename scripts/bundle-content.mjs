import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const extensionRoot = join(dirname(fileURLToPath(import.meta.url)), "..", "extension");
const order = [
  "src/settings.js",
  "src/i18n.js",
  "src/position.js",
  "src/extract-text.js",
  "src/insert-text.js",
  "src/clipboard.js",
  "src/live-adapter.js",
  "src/controller.js",
  "src/bootstrap.js"
];

function bundleFile(source) {
  const names = [];
  const code = source
    .replace(/^\s*import\s+[^;]+;\s*$/gm, "")
    .replace(/^export\s+(async\s+function|function|const|let|class)\s+([A-Za-z0-9_]+)/gm, (_, kind, name) => {
      names.push(name);
      return `${kind} ${name}`;
    });
  if (/^\s*export\s/m.test(code) || /^\s*import\s/m.test(code)) {
    throw new Error("Could not bundle a module statement");
  }
  return `const { ${names.join(", ")} } = (() => {\n${code}\nreturn { ${names.join(", ")} };\n})();\n`;
}

const parts = order.map((file) => bundleFile(readFileSync(join(extensionRoot, file), "utf8")));
const output = `/* Generated by scripts/bundle-content.mjs. Chrome loads this as a classic content script. */
(() => {
${parts.join("\n")}
startApp({
  chrome,
  window,
  document
}).catch((error) => {
  const name = error && typeof error.name === "string" ? error.name : "Error";
  console.error("[Dot Copy Paste]", name);
});
})();
`;
writeFileSync(join(extensionRoot, "content", "content.js"), output);
console.log("bundled content/content.js");
